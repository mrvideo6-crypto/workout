function libNorm(s) { return String(s || '').toLowerCase().replace(/ё/g, 'е').replace(/\s+/g, ' ').trim(); }
function libByName(name) {
  var n = libNorm(name);
  if (!n) return null;
  for (var i = 0; i < EXLIB.length; i++) if (libNorm(EXLIB[i].name) === n) return EXLIB[i];
  return null;
}
